# =========================================
# Arithmetic Operators
# =========================================

a = 20
b = 6

print("===== Arithmetic Operators =====")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponent:", a ** b)


# =========================================
# Assignment Operators
# =========================================

print("\n===== Assignment Operators =====")

num = 10
print("Initial value:", num)

num += 5 # num = num + 5
print("After += 5 :", num)

num -= 3 # num = num - 3
print("After -= 3 :", num)

num *= 2 # num = num * 2
print("After *= 2 :", num)

num /= 4 # num = num / 4
print("After /= 4 :", num)


# =========================================
# Comparison Operators
# =========================================

print("\n===== Comparison Operators =====")
print("a == b :", a == b)
print("a != b :", a != b)
print("a > b  :", a > b)
print("a < b  :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)


# =========================================
# Logical Operators
# =========================================

x = True
y = False

print("\n===== Logical Operators =====")
print("x and y :", x and y)
print("x or y  :", x or y)
print("not x   :", not x)
